插件整体背景
OPDS、设置、历史、分类、评分、缓存架及指针阅读都使用同一个漫画插件全屏背景，加载、取消、返回和窗口切换期间保留。明确退出漫画插件时，先关闭插件窗口再撤背景，返回 KOReader。单独打开设置并关闭弹窗后，可按返回键或右上角关闭退出；书架加载期间返回键仍退到上一级。

漫画书架封面
左上角“切换连接”旁的视图按钮切换列表与封面；长按按钮查看说明。记住选择和浏览位置，列数沿用阅读设置中的3/5列。点文件夹封面进入目录，点书籍封面打开漫画，长按封面选择“进入漫画”或“缓存漫画”。底部“操作”保留刷新、历史、分类、评分和缓存等入口。
优先取文件夹直属图片中数字排序首张（001、2、10）；没有图片时先提取当前目录漫画书的第一页，再查下一层子文件夹，空子目录继续下一项。支持 ZIP/CBZ、RAR/CBR、7Z/CB7、TAR/CBT、图片 EPUB、MOBI/AZW/AZW3/PRC 和图片 PDF 的首张阅读图片；复杂 PDF 取决于设备的远程渲染能力。进入、返回及等待目录期间始终保留漫画插件背景。没有封面仍可点占位卡，纯归档/文档文件夹不为封面下载整本书。仅加载当前屏幕的卡片；刷新会重新选图。
“缓存管理 → 漫画书架封面缓存”或封面视图底部“设置”单独控制书架缓存：默认上限200MB、超过150MB触发清理、清到100MB、每10分钟检查。清理最久未浏览的封面和索引，使用中的文件保留；不会删除原漫画、阅读历史、正文缓存或密钥。已缓存目录可断网浏览，封面缓存不代表整本漫画离线。

翻页与设置
点按左右侧或左右滑动翻页；右到左模式会反转方向。点按画面中间打开阅读设置。点按屏幕顶部或底部各1/12高度的整条区域，打开 KOReader 默认菜单；横竖屏均按当前高度计算，整页、智能分格和动态面板视图都适用。对白命中仍优先放大，关闭对白浮层的那次点按不同时打开菜单；右上角双击仍用于退出。

灰度抖动与墨水屏刷新
先安装并启用 GrayDither 0.3.0 或以上；漫画正文点画面中间，选择“灰度抖动与墨水屏刷新”。两个开关独立保存、默认关闭，仅用于本来源的内置阅读器；缺失或禁用仍可正常阅读，保存失败保留原设置。
灰度抖动对最终正文进行 16 级软件 Floyd–Steinberg 处理，不改原图或解码缓存；不是硬件 256 级灰度。整页、拆页、适宽、象限、长条和分格均支持，气泡浮层及文字提示沿用原显示。
自动全刷间隔1～50次，默认5次；首次与同屏重绘、预加载、设置不计。新分片、长条位置和分格自由视图移动/缩放按新画面计一次。可选原生全刷或黑白辅助，黑白各保持0.1～1秒、默认0.3秒；立即全刷先返回正文。
共享自动全刷有效时临时暂停原每页全刷和页动画，原偏好保留，关闭或服务失效后恢复。加载保留计数并取消阶段任务，设置和休眠重建首屏基准，退出清理浮层与定时任务。黑白辅助会闪屏，残影与设备性能需真机验收。

原图与提示
去灰增强和亮度/对比度都关闭时不做这两项图像增强，也不显示“处理图像成功”；自动裁边与适屏仍按各自设置显示。所有增强和自动裁边都关闭时直接使用原图。
左上角提示出现、替换和消失时只刷新文字所在的小块区域。翻页、切换视图和主动整页刷新仍会更新漫画画面。

网格象限缩放
在正文中央打开“阅读设置 → 网格象限缩放”，独立开启，默认关闭。画面划分为左上、右上、左下、右下四个象限，可单独关闭十字辅助线。只有两指同时轻触才进入象限放大，按两指中心点选区，完整等比放大适屏；单指点按、双击和双指按住均不进入此功能，抬起手指不会自动还原。
放大后再双指轻触或单指点按恢复原画面。对白点击、关闭对白浮层、上下各1/12的 KOReader 菜单及右上双击退出优先。拆页时放大当前左/右半页，适宽时放大当前滚动位置，不跳到尚未显示的原图区域。开启“缩放期间右到左”后，放大时左右滑动采用漫画顺序，恢复、换页或退出后回到原方向，不修改 KOReader 全局设置。
点按选项只应用当前漫画，长按同一选项同时保存为新漫画默认；全局阅读设置中的“网格象限缩放默认值”用于直接调整默认。网格入口独立于宽图拆分，拆分首屏可在已有“宽图拆分设置”选择左边先或右边先。设备方向仍使用 KOReader 菜单或分格的手动旋转，本功能不自动改变设备方向。
开启网格时，双指轻触优先于整页的分格入口，分格仍可单指长按进入；进入分格后沿用其控制和缩放，不叠加网格。关闭网格恢复原分格双指入口和旧双指按住临时象限。旧临时象限需按住约半秒，松开任一指恢复；开启网格时暂停旧临时象限。加载、设置、错误、分格和长条连续视图不触发网格。

对白气泡放大
在“漫画阅读设置 → 图片显示”开启“气泡放大”，选择1.5、2或3倍；默认不开启。新设置默认“点按与长按”：点中封闭浅色对白先放大，优先于分格导航、中央设置和顶部菜单；没有可靠对白时继续原本操作，不吞掉翻格或设置。以前明确选过“长按”的设置保留，可切成“点按与长按”或“点按”。
整页和分格中的对白都可放大。浮层保持完整气泡并自动限制到屏内；点一下或滑动关闭，不翻页。双指按住期间不检测气泡。黑底白字、没有闭合轮廓、过小气泡或复杂闭合字形可能误识别；改点气泡空白处或使用象限放大。检测只用当前图像，不重新下载或保存进度。

智能分格阅读
使用默认引擎，图片显示设为整页，开启智能分格。长按非对白区域进入；开启气泡后，命中对白优先放大，未命中继续进入分格。“更多分格设置 → 触发手势与导航”可选长按、两指轻敲或都启用。开启网格时整页的两指轻敲用于网格，长按仍进入分格；关闭网格恢复分格入口及旧临时象限。
中央点按打开分格视图控制。首个按钮切换 Panel Cut（独立格）、Pan & Zoom（保留整页上下文、移动取景窗口）、Free View（整页自由缩放和拖动，不切格或翻页）。自由视图直接打开整页，不要求先识别出分格；切回逐格模式时重新识别，不能可靠识别则保留自由视图。
控制内有放大、缩小、只旋转分格、左右/上下导航、反向操作、左到右/右到左顺序、截图和“旋转整个设备”。旋转图片不改变设备方向或阅读顺序。截图保存当前放大的画面到 KOReader 截图目录，隐藏按钮、进度条和提示，不重新下载漫画。
“更多分格设置”按过渡、手势导航、裁切识别分组：经典直接切换，墨水屏默认推荐；动画为白场淡出淡入；平滑在同页的分格之间移动取景窗口，适合安卓和桌面。时长可选0.15/0.3/0.5/0.8秒，帧数3/5/8/12。可选跨页淡入；跨页不拼接两页大画布。实际时长还受设备绘图速度影响。
低内存、没有调度/绘图支持或 GrayDither 自动刷新接管时退回经典。退出、换页及调整设置会停止或先完成过渡，避免旧定时任务覆盖新画面。
边缘点按和滑动切格可以分别关闭；两侧点按区域可选15%/25%/33%。可以选择严格原框裁切或对白保护范围（默认保护），显示邻近内容、0/2/5/10%边距、识别阈值25/40/55/70，以及自动/浅色/深色背景。严格裁切可能截掉伸出框外的对白，建议保留对白保护。
点按视图或设置只应用于当前漫画，长按同一项同时作为新漫画默认值；放大/拖动是当前画面的临时操作。独立的全局阅读设置用于默认配置。
最后一格继续前进进入下一页；识别失败、候选过多、框线布局不确定或内容保护范围过大时，仅当前页显示完整画面，保留智能分格状态，下一页继续识别。自由视图不翻页，需先切回逐格视图。关闭分格或主动退出恢复整页；原生加载/渲染错误仍提示。
分格框用于排序，扩大的对白范围用于显示。复杂斜格、无框、嵌套格并非都能可靠识别；可用自由视图完整查看。三视图行为重点参考 Meguru，导航、截图与过渡参考 PanelsPlus，对白手势参考 BubbleZoom；没有引入它们的独立书库或 OCR 功能。


动态面板变焦
在漫画阅读设置中单独开启“动态面板变焦”；开启它会关闭智能分格，开启智能分格也会关闭动态模式。两个模式的顺序、边距与缩放配置独立保存。使用默认图片引擎、整页显示，长按进入动态面板；先检测当前页，后续逐页实时检测，不扫描整本漫画。
使用 KOReader 自带的 Leptonica 原生引擎识别格框。面板置中并隔离相邻内容，只保留当前格和下一格预渲染图；预加载尚未完成时仍需短暂渲染，不保证每次零等待。
动态控制可选跟随翻页方向、左到右或右到左，以及聚焦留白、长按原图扩展和自由缩放倍率。点按设置应用当前漫画，长按同时作为新漫画默认。中央点按或两指轻敲打开动态控制，左右边缘点按和左右滑动依阅读顺序切格。
动态面板中长按进入自由缩放，可双指缩放和拖动画面，关闭原生缩放后返回原格。长按读取格框周围实际原图，扩展可选2/5/10/15/20%，用于查看伸出格框的对白；没有新增OCR或生成缺失文字。开启气泡放大时，命中对白仍优先放大。
未识别到面板时该页显示整页，下一页继续识别。复杂、无框或连在一起的面板不保证准确；原生能力缺失或加载失败会提示并恢复整页。动态模式保持经典切换，不改变智能分格的三视图与过渡设置。设备触摸、速度和墨水屏效果需实际验收。

