漫画书架封面
左上角“切换连接”旁的视图按钮切换列表与封面；长按按钮查看说明。记住选择和浏览位置，列数沿用阅读设置中的3/5列。点封面进入文件夹，长按封面选择“进入漫画”或“缓存漫画”。底部“操作”保留刷新、历史、分类、评分和缓存等入口。
优先取文件夹直属图片中数字排序首张（001、2、10）；没有图片时只查下一层子文件夹，空子目录继续下一项。没有封面仍可点占位卡，纯归档/文档文件夹不为封面下载整本书。仅加载当前屏幕的卡片；刷新会重新选图。
“缓存管理 → 漫画书架封面缓存”或封面视图底部“设置”单独控制书架缓存：默认上限200MB、超过150MB触发清理、清到100MB、每10分钟检查。清理最久未浏览的封面和索引，使用中的文件保留；不会删除原漫画、阅读历史、正文缓存或密钥。已缓存目录可断网浏览，封面缓存不代表整本漫画离线。

翻页与设置
点按左右侧或左右滑动翻页；右到左模式会反转方向。点按画面中间打开阅读设置，顶部中间打开 KOReader 菜单。

原图与提示
去灰增强和亮度/对比度都关闭时不做这两项图像增强，也不显示“处理图像成功”；自动裁边与适屏仍按各自设置显示。所有增强和自动裁边都关闭时直接使用原图。
左上角提示出现、替换和消失时只刷新文字所在的小块区域。翻页、切换视图和主动整页刷新仍会更新漫画画面。

双指象限放大
双指同时按住约半秒，以双指中心点选择左上、右上、左下或右下象限。按住期间移动不切换象限，松开任一指恢复原画面、显示位置及先前锁定的象限。
双指点按仍可锁定象限，再点按恢复。加载、设置和分格界面不触发象限放大。

对白气泡放大
在“漫画阅读设置 → 图片显示”开启“气泡放大”，选择1.5、2或3倍。默认关闭，开启后默认单指长按对白内部：识别封闭的浅色对白区域，并在原页上显示放大浮层。长按松开后浮层保留，点一下或滑动关闭，当前页和阅读位置不变。
浮层自动移到屏内；空间不够时降低倍率，保持完整气泡。留白、空对白、没有可靠轮廓、黑底白字或过小气泡可能无法识别。复杂闭合字形（如“回”）可能误识别为局部字形；出现提示或放大区域不对时，关闭后改按对白空白处重试，或使用双指象限放大。
可选“单指点按”触发：开启后正文点按用于气泡放大，滑动仍可翻页；顶部中间仍可打开 KOReader 菜单。在全局漫画阅读设置中可切回长按或关闭。
气泡长按优先于整页的智能分格入口；关闭气泡放大后恢复原长按操作。在已进入的分格界面仍使用原分格操作。双指按住时不能同时打开气泡。
气泡检测只使用当前显示图片，不重新下载、解码或保存阅读进度；换页、切换设置、休眠和退出会关闭浮层。

智能分格阅读
使用默认引擎，在“漫画阅读设置 → 智能分格阅读”开启，并将图片显示设为整页。整页长按进入分格；气泡放大开启时，长按优先识别气泡，可先关闭气泡放大再进入分格。
点按分格中间打开控制：保留周边、独立格、自由视图三个模式依次切换。保留周边以完整对白为取景范围，尽量显示邻近画面；独立格单独显示带保护范围的当前格；自由视图显示整页，可以双指缩放、滑动或拖动，不切换分格或翻页。
“旋转”每次顺时针90°，可选择0°、90°、180°、270°，只旋转当前分格显示，不改变设备方向、原图和阅读顺序。可分别设置左右/上下导航、操作正向/反向，以及左到右/右到左的分格顺序。旋转后仍按所选屏幕方向操作。
导航模式点按对应轴的边缘或沿该轴滑动切换分格，硬件翻页键也可使用；最后一格继续前进进入下一页。自由视图只缩放与拖动，返回控制切换视图后才恢复逐格导航。
点按视图、旋转、方向、顺序或分格设置只应用于当前漫画；长按同一设置同时应用于当前漫画，并作为新漫画默认值。不同漫画可保留各自设置；全局“智能分格阅读默认值”用于默认设置。放大/缩小按钮是临时操作。
“继续看当前格”关闭控制；“退出分格 → 整页”恢复原页及原来的拆分、裁边和位置。分格内长按仍可打开KOReader原生自由缩放，关闭后返回当前格。
检测使用整张当前图片，框线用于排序，扩大的对白保护范围仅用于显示。格线相连、无框、斜格或复杂嵌套可能无法可靠分开。未识别到有效分格或候选过多时，只将当前页完整适屏显示，并保留智能分格状态；按所选方向翻到下一页会继续检测，不必重新长按进入。主动退出、关闭分格或切换不支持分格的图片引擎时结束该状态。真正的加载或渲染错误仍单独提示。
这不是文字识别，不能保证任意对白和布局都精准。发现漏格时可切自由视图或退出分格，保留完整内容。
三种视图交互参考Meguru，组件检测与排序有限适配Panels+；没有移植它们的独立阅读器和过渡动画。当前以直接切换画面为主。

